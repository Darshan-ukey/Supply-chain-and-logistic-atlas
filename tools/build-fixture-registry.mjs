import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalHash } from '../lib/readiness/canonicalize.mjs';

// Atlas AR0.3 — F2 fixture registry builder.
//
// ChatGPT re-QA correction: `scope_class: SYNTHETIC_FIXTURE` was self-asserted, so a real
// governed scope could escape its BLOCK by editing one string. Fixture status must instead be
// bound to a frozen registry entry with an exact content hash.
//
// The registry it emits is an F2 freeze asset. Regenerating it is a governed act: any content
// change to a fixture changes its hash and must be re-frozen deliberately, never silently.
//
// The content hash deliberately EXCLUDES `fixture_identity` itself, since including the
// identity inside the hash it names would be circular.

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FIXTURES = path.join(HERE, '..', 'tests', 'fixtures', 'ar0-3-readiness');
const OUT = path.join(HERE, '..', 'lib', 'readiness', 'fixture-registry.mjs');

export function fixtureContentHash(manifest) {
  const { fixture_identity, ...content } = manifest ?? {};
  return canonicalHash(content);
}

const entries = {};
for (const file of fs.readdirSync(FIXTURES).filter(f => f.endsWith('.json')).sort()) {
  const manifest = JSON.parse(fs.readFileSync(path.join(FIXTURES, file), 'utf8'));
  const id = manifest?.fixture_identity?.fixture_id;
  if (!id) { console.error(`SKIP ${file}: no fixture_identity`); continue; }
  entries[id] = {
    fixture_id: id,
    fixture_version: manifest.fixture_identity.fixture_version,
    content_hash: fixtureContentHash(manifest),
    source_file: `tests/fixtures/ar0-3-readiness/${file}`
  };
}

const body = `// GENERATED by tools/build-fixture-registry.mjs — do not hand-edit.
//
// F2 frozen fixture registry. Binds SYNTHETIC_FIXTURE status to an exact content hash so a
// scope cannot grant itself fixture privileges by self-assertion. An unregistered scope
// defaults to governed and therefore BLOCKS while the upstream completeness contract is
// unavailable.
//
// Regenerate deliberately: node tools/build-fixture-registry.mjs

export const FROZEN_FIXTURE_REGISTRY = Object.freeze(${JSON.stringify(entries, null, 2)});

export const REGISTRY_ENTRY_COUNT = ${Object.keys(entries).length};
`;
fs.writeFileSync(OUT, body);
console.log(`registered ${Object.keys(entries).length} fixtures -> lib/readiness/fixture-registry.mjs`);
